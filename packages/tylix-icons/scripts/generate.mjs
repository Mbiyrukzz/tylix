// Generates every icon format from src/icons.json, the one source of truth:
//
//   icons/Icon*.tyx + tylix-components.json   native Tylix pages
//   react/    forwardRef components           import { IconBell } from 'tylix-icons/react'
//   vue/      functional components           import { IconBell } from 'tylix-icons/vue'
//   svelte/   Svelte 5 components             import { IconBell } from 'tylix-icons/svelte'
//   angular/  standalone components, partially compiled (as Angular
//             libraries ship on npm, linked by the app's build)
//                                             import { IconBell } from 'tylix-icons/angular'
//
// Run after editing src/icons.json:  npm run generate (in packages/tylix-icons)
//
// Each icon is its own module (or a pure call), so apps only bundle the
// icons they import.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const icons = JSON.parse(fs.readFileSync(path.join(root, 'src/icons.json'), 'utf-8'))
const names = Object.keys(icons).sort()

const HEADER = '// Generated by scripts/generate.mjs from src/icons.json. Do not edit.\n'

// "<path d='M1 2'/><circle cx='1'/>" -> [['path', { d: 'M1 2' }], ['circle', { cx: '1' }]]
function parse(markup) {
  const nodes = []
  for (const [, tag, attrs] of markup.matchAll(/<(path|circle|rect|ellipse)((?: [a-z-]+='[^']*')+)\/>/g)) {
    nodes.push([tag, Object.fromEntries([...attrs.matchAll(/ ([a-z-]+)='([^']*)'/g)].map((m) => [m[1], m[2]]))])
  }
  if (nodes.length === 0) throw new Error(`Could not parse icon markup: ${markup}`)
  return nodes
}

const attrString = (attrs) =>
  Object.entries(attrs)
    .map(([key, value]) => `${key}="${value}"`)
    .join(' ')
const markupOf = (nodes) => nodes.map(([tag, attrs]) => `<${tag} ${attrString(attrs)}/>`).join('')
const camel = (key) => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase()

function write(file, content) {
  const full = path.join(root, file)
  fs.mkdirSync(path.dirname(full), { recursive: true })
  fs.writeFileSync(full, content)
}

function clean(dir) {
  fs.rmSync(path.join(root, dir), { recursive: true, force: true })
}

const parsed = Object.fromEntries(names.map((name) => [name, parse(icons[name])]))

// ---- native .tyx -------------------------------------------------------

clean('icons')
const manifest = {}
for (const name of names) {
  write(
    `icons/Icon${name}.tyx`,
    `component Icon${name}

props
  class?: string

template
  <svg class='{{ class or "w-5 h-5" }}' fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">
    ${markupOf(parsed[name])}
  </svg>
`,
  )
  manifest[`Icon${name}`] = `icons/Icon${name}.tyx`
}
write('tylix-components.json', JSON.stringify(manifest, null, 2) + '\n')

// ---- React -------------------------------------------------------------

const reactNodes = (nodes) =>
  JSON.stringify(nodes.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).map(([k, v]) => [camel(k), v]))]))

write(
  'react/index.js',
  `${HEADER}import { createElement, forwardRef } from 'react'

// <IconBell />, <IconBell size={16} className="text-rose-500" title="Alerts" />
// Without a title the icon is decorative (aria-hidden); with one it is
// announced as an image. Other props go to the <svg>.
function icon(displayName, nodes) {
  const Icon = forwardRef(function Icon({ size = 20, strokeWidth = 1.5, title, children, ...rest }, ref) {
    return createElement(
      'svg',
      {
        xmlns: 'http://www.w3.org/2000/svg',
        width: size,
        height: size,
        viewBox: '0 0 24 24',
        fill: 'none',
        stroke: 'currentColor',
        strokeWidth,
        strokeLinecap: 'round',
        strokeLinejoin: 'round',
        'aria-hidden': title ? undefined : true,
        role: title ? 'img' : undefined,
        ref,
        ...rest,
      },
      title ? createElement('title', null, title) : null,
      ...nodes.map(([tag, attrs], key) => createElement(tag, { key, ...attrs })),
      children,
    )
  })
  Icon.displayName = displayName
  return Icon
}

${names.map((name) => `export const Icon${name} = /* @__PURE__ */ icon('Icon${name}', ${reactNodes(parsed[name])})`).join('\n')}
`,
)
write(
  'react/index.d.ts',
  `${HEADER}import type { ForwardRefExoticComponent, RefAttributes, SVGProps } from 'react'

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  /** Width and height in pixels (or any CSS length). Default 20. */
  size?: number | string
  /** Default 1.5. */
  strokeWidth?: number | string
  /** Makes the icon announced to screen readers; otherwise it is decorative. */
  title?: string
}

export type Icon = ForwardRefExoticComponent<IconProps & RefAttributes<SVGSVGElement>>

${names.map((name) => `export declare const Icon${name}: Icon`).join('\n')}
`,
)

// ---- Vue ---------------------------------------------------------------

write(
  'vue/index.js',
  `${HEADER}import { h } from 'vue'

// <IconBell />, <IconBell :size="16" class="text-rose-500" title="Alerts" />
// class, style and other attributes fall through to the <svg>.
const props = {
  size: { type: [Number, String], default: 20 },
  strokeWidth: { type: [Number, String], default: 1.5 },
  title: { type: String, default: undefined },
}

function icon(name, nodes) {
  const Icon = (p) =>
    h(
      'svg',
      {
        xmlns: 'http://www.w3.org/2000/svg',
        width: p.size,
        height: p.size,
        viewBox: '0 0 24 24',
        fill: 'none',
        stroke: 'currentColor',
        'stroke-width': p.strokeWidth,
        'stroke-linecap': 'round',
        'stroke-linejoin': 'round',
        'aria-hidden': p.title ? undefined : 'true',
        role: p.title ? 'img' : undefined,
      },
      [p.title ? h('title', p.title) : null, ...nodes.map(([tag, attrs]) => h(tag, attrs))],
    )
  Icon.props = props
  Icon.displayName = name
  return Icon
}

${names.map((name) => `export const Icon${name} = /* @__PURE__ */ icon('Icon${name}', ${JSON.stringify(parsed[name])})`).join('\n')}
`,
)
write(
  'vue/index.d.ts',
  `${HEADER}import type { FunctionalComponent, SVGAttributes } from 'vue'

export interface IconProps extends /* @vue-ignore */ SVGAttributes {
  /** Width and height in pixels (or any CSS length). Default 20. */
  size?: number | string
  /** Default 1.5. */
  strokeWidth?: number | string
  /** Makes the icon announced to screen readers; otherwise it is decorative. */
  title?: string
}

export type Icon = FunctionalComponent<IconProps>

${names.map((name) => `export declare const Icon${name}: Icon`).join('\n')}
`,
)

// ---- Svelte ------------------------------------------------------------

clean('svelte')
for (const name of names) {
  write(
    `svelte/Icon${name}.svelte`,
    `<!-- Generated by scripts/generate.mjs from src/icons.json. Do not edit. -->
<script>
  let { size = 20, strokeWidth = 1.5, title = undefined, ...rest } = $props()
</script>

<svg
  xmlns="http://www.w3.org/2000/svg"
  width={size}
  height={size}
  viewBox="0 0 24 24"
  fill="none"
  stroke="currentColor"
  stroke-width={strokeWidth}
  stroke-linecap="round"
  stroke-linejoin="round"
  aria-hidden={title ? undefined : 'true'}
  role={title ? 'img' : undefined}
  {...rest}
>{#if title}<title>{title}</title>{/if}${markupOf(parsed[name])}</svg>
`,
  )
}
write(
  'svelte/index.js',
  `${HEADER}// <IconBell />, <IconBell size={16} class="text-rose-500" title="Alerts" />
${names.map((name) => `export { default as Icon${name} } from './Icon${name}.svelte'`).join('\n')}
`,
)
write(
  'svelte/index.d.ts',
  `${HEADER}import type { Component } from 'svelte'
import type { SVGAttributes } from 'svelte/elements'

export interface IconProps extends SVGAttributes<SVGSVGElement> {
  /** Width and height in pixels (or any CSS length). Default 20. */
  size?: number | string
  /** Default 1.5. */
  strokeWidth?: number | string
  /** Makes the icon announced to screen readers; otherwise it is decorative. */
  title?: string
}

export type Icon = Component<IconProps>

${names.map((name) => `export declare const Icon${name}: Icon`).join('\n')}
`,
)

// ---- Angular -----------------------------------------------------------
// Partial declarations, the format ngc emits for libraries: the app's
// Angular build links them like any npm Angular library. They live in
// fesm2022/*.mjs, the Angular Package Format layout, because Angular's
// Vite plugin only runs its linker on files there.

clean('angular')
const NG_VERSION = '20.0.0'
const NG_STYLE =
  ':where([data-tylix-icon]){display:inline-block;width:1.25rem;height:1.25rem;flex-shrink:0;vertical-align:middle}:where([data-tylix-icon])>svg{display:block;width:100%;height:100%}'
const signalInput = (name) =>
  `${name}: { classPropertyName: "${name}", publicName: "${name}", isSignal: true, isRequired: false, transformFunction: null }`

for (const name of names) {
  const cls = `Icon${name}`
  const template = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" [attr.stroke-width]="strokeWidth()" stroke-linecap="round" stroke-linejoin="round">@if (title()) {<title>{{ title() }}</title>}${markupOf(parsed[name])}</svg>`
  write(
    `angular/fesm2022/${cls}.mjs`,
    `${HEADER}import * as i0 from '@angular/core'

export class ${cls} {
  size = i0.input(null)
  strokeWidth = i0.input(1.5)
  title = i0.input(null)
  static ɵfac = i0.ɵɵngDeclareFactory({ minVersion: "12.0.0", version: "${NG_VERSION}", ngImport: i0, type: ${cls}, deps: [], target: i0.ɵɵFactoryTarget.Component })
  static ɵcmp = i0.ɵɵngDeclareComponent({ minVersion: "17.1.0", version: "${NG_VERSION}", type: ${cls}, isStandalone: true, selector: "icon-${kebab(name)}", inputs: { ${['size', 'strokeWidth', 'title'].map(signalInput).join(', ')} }, host: { attributes: { "data-tylix-icon": "" }, properties: { "style.width.px": "size()", "style.height.px": "size()", "attr.role": "title() ? \\"img\\" : null", "attr.aria-hidden": "title() ? null : \\"true\\"" } }, ngImport: i0, template: ${JSON.stringify(template)}, isInline: true, styles: [${JSON.stringify(NG_STYLE)}], changeDetection: i0.ChangeDetectionStrategy.OnPush, encapsulation: i0.ViewEncapsulation.None })
}
`,
  )
}
write(
  'angular/fesm2022/index.mjs',
  `${HEADER}// <icon-bell />, <icon-bell class="w-4 h-4 text-rose-500" title="Alerts" />
// Size with classes (default 1.25rem) or [size]="16" for pixels. List the
// icons a component uses in its imports: imports: [IconBell].
${names.map((name) => `export { Icon${name} } from './Icon${name}.mjs'`).join('\n')}
`,
)
write(
  'angular/index.d.ts',
  `${HEADER}import * as i0 from '@angular/core'

type IconInputs = {
  size: { alias: 'size'; required: false; isSignal: true }
  strokeWidth: { alias: 'strokeWidth'; required: false; isSignal: true }
  title: { alias: 'title'; required: false; isSignal: true }
}

declare abstract class TylixIcon {
  /** Width and height in pixels. Unset: 1.25rem, or whatever your classes say. */
  readonly size: i0.InputSignal<number | null>
  /** Default 1.5. */
  readonly strokeWidth: i0.InputSignal<number | string>
  /** Makes the icon announced to screen readers; otherwise it is decorative. */
  readonly title: i0.InputSignal<string | null>
}

${names
  .map(
    (name) => `export declare class Icon${name} extends TylixIcon {
  static ɵfac: i0.ɵɵFactoryDeclaration<Icon${name}, never>
  static ɵcmp: i0.ɵɵComponentDeclaration<Icon${name}, 'icon-${kebab(name)}', never, IconInputs, {}, never, never, true, never>
}`,
  )
  .join('\n')}
`,
)

// ---- raw data ----------------------------------------------------------

write(
  'data/index.js',
  `${HEADER}// Each icon's inner SVG markup (24x24, stroke 1.5, round caps), for
// building your own wrapper.
export const icons = ${JSON.stringify(Object.fromEntries(names.map((name) => [name, markupOf(parsed[name])])))}
`,
)
write('data/index.d.ts', `${HEADER}export declare const icons: Record<string, string>\n`)

console.log(`Generated ${names.length} icons for tylix, react, vue, svelte and angular.`)
