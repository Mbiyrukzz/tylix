function timestamp() {
  return new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)
}

async function writeIfMissing(baseDir, file, content, written, kept) {
  const rel = path.relative(baseDir, file)
  if (await exists(file)) {
    kept.push(rel)
    return false
  }
  await fs.mkdir(path.dirname(file), { recursive: true })
  await fs.writeFile(file, content)
  written.push(rel)
  return true
}

// Adds `import { accessRoutes }` and a call inside protectedRoutes().
export function patchWebRoutes(source, ext) {
  if (source.includes('accessRoutes(')) return source
  const importLine = `import { accessRoutes } from './access.${'js'}'\n`
  const lines = source.split('\n')
  let lastImport = -1
  lines.forEach((line, i) => {
    if (/^import\s/.test(line)) lastImport = i
  })
  lines.splice(lastImport + 1, 0, importLine.trimEnd())
  let out = lines.join('\n')
  const fn = /export\s+async\s+function\s+protectedRoutes\s*\(([^)]*)\)\s*(?::\s*[^{]+)?\{/
  const match = fn.exec(out)
  if (match) {
    const at = match.index + match[0].length
    out = `${out.slice(0, at)}\n  // Roles and permissions admin API (app/routes/access)\n  accessRoutes(router)\n${out.slice(at)}`
  } else {
    out += `\n// Every route here requires a logged-in user.\nexport async function protectedRoutes(router${ext === 'ts' ? ': Router' : ''}) {\n  accessRoutes(router)\n}\n`
    if (ext === 'ts' && !/import\s+type\s+\{[^}]*Router/.test(out)) out = `import type { Router } from '@tylix/core'\n${out}`
  }
  return out
}

export function patchDatabaseSeeder(source) {
  if (source.includes('PermissionSeeder')) return source
  const importLine = "import { seed as seedPermissions } from './PermissionSeeder.js'"
  const lines = source.split('\n')
  let lastImport = -1
  lines.forEach((line, i) => {
    if (/^import\s/.test(line)) lastImport = i
  })
  lines.splice(lastImport + 1, 0, ...(lastImport === -1 ? [importLine, ''] : [importLine]))
  let out = lines.join('\n')
  const fn = /export\s+async\s+function\s+seed\s*\([^)]*\)\s*(?::\s*[^{]+)?\{/
  const match = fn.exec(out)
  if (!match) return null
  const at = match.index + match[0].length
  return `${out.slice(0, at)}\n  // Roles and permissions from app/permissions\n  await seedPermissions()\n${out.slice(at)}`
}

export async function makePermissions({ baseDir = process.cwd(), quiet = false } = {}) {
  const ts = (await detectLanguage(baseDir)) === 'typescript'
  const ext = ts ? 'ts' : 'js'
  const written = []
  const kept = []
  const notes = []
  const app = (...p) => path.join(baseDir, 'app', ...p)

  await writeIfMissing(baseDir, app(`permissions.${ext}`), permissionsConfigSource(ts), written, kept)
  await writeIfMissing(baseDir, app('models', `Role.${ext}`), roleModelSource(ts), written, kept)
  await writeIfMissing(baseDir, app('models', `Permission.${ext}`), permissionModelSource(ts), written, kept)
  await writeIfMissing(baseDir, app('seeders', `PermissionSeeder.${ext}`), seederSource(ts), written, kept)

  const migrationsDir = path.join(baseDir, 'database', 'migrations')
  const existingMigration = (await fs.readdir(migrationsDir).catch(() => [])).find((f) => /^\d{14}_create_permission_tables\.(js|ts)$/.test(f))
  if (existingMigration) kept.push(path.join('database', 'migrations', existingMigration))
  else await writeIfMissing(baseDir, path.join(migrationsDir, `${timestamp()}_create_permission_tables.${ext}`), migrationSource(ts), written, kept)

  const hasUsers = await exists(app('models', `User.${ext}`))
  if (hasUsers) {
    await writeIfMissing(baseDir, app('controllers', `AccessController.${ext}`), controllerSource(ts), written, kept)
    await writeIfMissing(baseDir, app('routes', `access.${ext}`), routesSource(ts), written, kept)
    const webFile = app('routes', `web.${ext}`)
    const web = (await exists(webFile)) ? await fs.readFile(webFile, 'utf-8') : null
    if (web === null) {
      await fs.writeFile(webFile, patchWebRoutes(ts ? "import type { Router } from '@tylix/core'\n" : '', ext))
      written.push(path.relative(baseDir, webFile))
    } else if (!web.includes('accessRoutes(')) {
      await fs.writeFile(webFile, patchWebRoutes(web, ext))
      written.push(`${path.relative(baseDir, webFile)} (registers the admin API)`)
    }
    if (await exists(app('pages'))) {
      await writeIfMissing(baseDir, app('pages', 'admin', 'access.tyx'), accessPageSource(), written, kept)
    } else {
      notes.push('This app has a React, Vue, Svelte or Angular frontend: build the admin screen on /api/admin/access (see the README of @tylix/permissions for components).')
    }
  } else {
    notes.push('No app/models/User yet, so the admin API and page were skipped. Run "tylix make:auth", then this again.')
  }

  const seederFile = app('seeders', `DatabaseSeeder.${ext}`)
  if (await exists(seederFile)) {
    const patched = patchDatabaseSeeder(await fs.readFile(seederFile, 'utf-8'))
    if (patched === null) notes.push(`Call seed() from app/seeders/PermissionSeeder.${ext} in your DatabaseSeeder.`)
    else if (patched !== (await fs.readFile(seederFile, 'utf-8'))) {
      await fs.writeFile(seederFile, patched)
      written.push(`${path.relative(baseDir, seederFile)} (runs PermissionSeeder)`)
    }
  }

  const pkgFile = path.join(baseDir, 'package.json')
  let needsInstall = false
  if (await exists(pkgFile)) {
    const pkg = JSON.parse(await fs.readFile(pkgFile, 'utf-8'))
    if (!pkg.dependencies?.['@tylix/permissions']) {
      pkg.dependencies = { ...(pkg.dependencies ?? {}), '@tylix/permissions': `^${cliVersion}` }
      await fs.writeFile(pkgFile, `${JSON.stringify(pkg, null, 2)}\n`)
      written.push('package.json (@tylix/permissions)')
      needsInstall = true
    }
  }

  if (!quiet) {
    console.log('\n✔ Roles and permissions\n')
    for (const f of written) console.log(`  + ${f}`)
    for (const f of kept) console.log(`  = ${f} (kept)`)
    for (const n of notes) console.log(`\n  ${n}`)
    console.log(
      `\nNext:\n${needsInstall ? '  npm install\n' : ''}  tylix migrate\n  tylix db:seed                      creates the starting roles\n  tylix permission:assign admin you@example.com\n\n` +
        `Then open /admin/access to manage roles, permissions and users.\n` +
        `Guard routes with permissions.middleware('posts.create'); check pages with can("posts.create").`,
    )
  }
  return { written, kept, notes }
}
