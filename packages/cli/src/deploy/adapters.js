// Deployment adapters: "tylix deploy:init <name>" writes the files a host
// needs. Server adapters run "tylix start" (plus the queue worker and the
// scheduler where the host has background processes); static adapters
// publish the output of "tylix export".
//
// A plugin can add one:
//   deployAdapters: { mycloud: { name: 'mycloud', label: 'My Cloud', files(ctx) { return { 'mycloud.json': '...' } } } }

const NODE_VERSION = '22'

const run = (ctx, script) => {
  const pm = ctx.packageManager
  if (pm === 'npm') return `npx tylix ${script}`
  if (pm === 'yarn') return `yarn tylix ${script}`
  if (pm === 'bun') return `bunx tylix ${script}`
  return `${pm} exec tylix ${script}`
}

const install = (ctx, { production = false } = {}) => {
  switch (ctx.packageManager) {
    case 'pnpm':
      return `corepack enable && pnpm install --frozen-lockfile${production ? ' --prod' : ''}`
    case 'yarn':
      return `corepack enable && yarn install --immutable`
    case 'bun':
      return `bun install --frozen-lockfile${production ? ' --production' : ''}`
    default:
      return production ? 'npm ci --omit=dev' : 'npm ci'
  }
}

const lockfile = {
  npm: 'package-lock.json',
  pnpm: 'pnpm-lock.yaml',
  yarn: 'yarn.lock',
  bun: 'bun.lockb',
}

const usesSqlite = (ctx) => (ctx.config.database?.driver ?? 'sqlite') === 'sqlite'

function dockerfile(ctx) {
  // Hosted frontends and TypeScript run from source (tsx), so dev
  // dependencies stay installed: the build tools are needed at runtime.
  return `# Generated by "tylix deploy:init docker". Edit freely.
FROM node:${NODE_VERSION}-slim AS build
WORKDIR /app
COPY package.json ${lockfile[ctx.packageManager] ?? 'package-lock.json'}* ./
RUN ${install(ctx)}
COPY . .
RUN ${run(ctx, 'build')}

FROM node:${NODE_VERSION}-slim
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=3000
ENV LOG_STACK=console
COPY --from=build /app /app
${usesSqlite(ctx) ? '# SQLite: keep the database on a volume mounted at /data.\nENV DATABASE_DRIVER=sqlite\nENV DATABASE_FILENAME=/data/database.sqlite\nRUN mkdir -p /data\nVOLUME /data\n' : ''}EXPOSE 3000
# Migrations run on every start; they are skipped when there is nothing new.
CMD ["sh", "-c", "${run(ctx, 'migrate')} && ${run(ctx, 'start')}"]
`
}

