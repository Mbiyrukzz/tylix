import { test } from 'node:test'
import assert from 'node:assert/strict'
import {
  diagnoseTyx,
  detectTyxKind,
  formatDiagnostic,
  offsetToPosition,
} from './diagnose.js'

const first = (source, options) => diagnoseTyx(source, options).diagnostics[0]
const at = (d) => `${d.line}:${d.column}`

test('only page, component and capability files are Tylix', () => {
  assert.equal(detectTyxKind('page Home\n').kind, 'page')
  assert.equal(detectTyxKind('  component Card\n').kind, 'component')
  assert.equal(detectTyxKind('capability Posts\n').name, 'Posts')
  // generator templates share the .tyx extension
  const generator = '/**\n * Generated by Tylix\n */\nimport { {{Model}} } from "x"\n'
  assert.deepEqual(diagnoseTyx(generator), {
    kind: 'other',
    name: null,
    diagnostics: [],
    symbols: [],
    imports: [],
  })
})

test('offsetToPosition is 1-based', () => {
  assert.deepEqual(offsetToPosition('ab\ncd', 0), { line: 1, column: 1 })
  assert.deepEqual(offsetToPosition('ab\ncd', 4), { line: 2, column: 2 })
})

test('a clean page has no diagnostics and lists its symbols', () => {
  const r = diagnoseTyx(`page Home

props
  id: string

state
  count(number): 0

computed
  double() {
    return this.count * 2
  }

action
  async save(id: string) {
    return id
  }

onMount
  async {
    await this.save("x")
  }

template
  <p>{{ count }} {{ double }}</p>
`)
  assert.deepEqual(r.diagnostics, [])
  assert.deepEqual(
    r.symbols.map((s) => `${s.kind} ${s.name} ${s.line}`),
    [
      'prop id 4',
      'state count 7',
      'computed double 10',
      'action save 15',
      'lifecycle onMount 19',
    ],
  )
  assert.equal(r.symbols.find((s) => s.name === 'save').detail, 'async save(id: string)')
})

test('script errors point at the file line and column', () => {
  const d = first(`page A

state
  count: 0

action
  inc() {
    this.count = = 1
  }

template
  <p>{{ count }}</p>
`)
  assert.equal(at(d), '8:18')
  assert.equal(d.message, 'Unexpected "="')
  assert.equal(d.origin, 'syntax')
})

test('template interpolation errors point inside the {{ }}', () => {
  const d = first(`page A

template
  <div>
    <p>{{ count + }}</p>
  </div>
`)
  assert.equal(at(d), '5:18')
})

test('attribute expression errors point inside the attribute', () => {
  const d = first(`page A\n\ntemplate\n  <input value="{{ a b }}" />\n`)
  assert.equal(at(d), '4:22')
  assert.match(d.message, /Unexpected "b"/)
})

test('{{#if}} and {{#each}} header errors are located', () => {
  assert.equal(
    at(first(`page A\n\ntemplate\n  {{#if a + }}\n    <p/>\n  {{/if}}\n`)),
    '4:12',
  )
  assert.equal(
    at(first(`page A\n\ntemplate\n  {{#each x in items. }}\n    <p/>\n  {{/each}}\n`)),
    '4:22',
  )
})

test('unclosed tags and blocks point at where they were opened', () => {
  assert.equal(at(first(`page A\n\ntemplate\n  <div>\n    <span>hi</span>\n`)), '4:3')
  assert.equal(at(first(`page A\n\ntemplate\n  <p/>\n  {{#if a}}\n    <p/>\n`)), '5:3')
})

test('a mismatched closing tag is underlined', () => {
  const d = first(`page A\n\ntemplate\n  <div>\n  </span>\n`)
  assert.equal(at(d), '5:3')
  assert.equal(d.length, '</span>'.length)
})

test('an unclosed bracket that hides the template is found', () => {
  const d = first(`page A\n\naction\n  go( {\n  }\n\ntemplate\n  <p/>\n`)
  assert.equal(at(d), '4:5')
  assert.match(d.message, /"\(" is never closed/)
})

test('lines below import lines keep their numbers', () => {
  const d = first(`component Card

import { IconX } from "tylix-icons"
import Badge from "./Badge"

template
  <p>{{ a + }}</p>
`)
  assert.equal(at(d), '7:12')
})

test('capability errors are located', () => {
  const d = first(`capability X\n\naction\n  go() {\n    return )\n  }\n`)
  assert.equal(at(d), '5:12')
})

test('typecheck diagnostics map to script and template lines', () => {
  const r = diagnoseTyx(
    `page A

state
  count(number): 0

action
  inc() {
    const s: string = this.count
  }

template
  <div>
    <p>{{ count.toFixed("a") }}</p>
  </div>
`,
    { typecheck: true },
  )
  assert.deepEqual(
    r.diagnostics.map((d) => `${d.origin} ${d.line}`),
    ['typecheck 8', 'typecheck 13'],
  )
})

test('components are typechecked too', () => {
  const r = diagnoseTyx(
    `component B\n\nprops\n  n: number\n\ntemplate\n  <p>{{ props.n.toUpperCase() }}</p>\n`,
    { typecheck: true },
  )
  assert.equal(r.diagnostics.length, 1)
  assert.equal(r.diagnostics[0].line, 7)
})

test('typecheck is skipped while the file has syntax errors', () => {
  const r = diagnoseTyx(`page A\n\ntemplate\n  <p>{{ a + }}</p>\n`, { typecheck: true })
  assert.deepEqual(r.diagnostics.map((d) => d.origin), ['syntax'])
})

test('the language options are honoured', () => {
  const src = `page A\n\nstate\n  items: []\n\ntemplate\n  <p>{{ not items has 1 }}</p>\n`
  assert.equal(diagnoseTyx(src, { language: { not: 'loose' } }).diagnostics.length, 0)
  assert.equal(
    diagnoseTyx(src, { language: { not: 'nope' } }).diagnostics[0].origin,
    'config',
  )
})

test('formatDiagnostic prints a code frame with a caret', () => {
  const src = `page A\n\ntemplate\n  <input value="{{ a b }}" />\n`
  const text = formatDiagnostic(src, first(src), 'A.tyx')
  assert.match(text, /^A\.tyx:4:22 {2}Unexpected "b"/)
  assert.match(text, /> 4 \|   <input value="\{\{ a b \}\}" \/>/)
  assert.match(text, /\n {4}\| {22}\^/)
})
